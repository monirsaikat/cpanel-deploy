export const VERSIONS = {
  checkout: 'actions/checkout@v7',
  setupPhp: 'shivammathur/setup-php@v2',
  setupNode: 'actions/setup-node@v7',
  ftpDeploy: 'SamKirkland/FTP-Deploy-Action@v4.4.0',
};

export const SITE_URL = 'https://saikat.polapain.net/cpanel-deploy';

export const EXCLUDE_PRESETS = [
  { value: '**/.git*', label: '.git, .gitignore, .github', always: true },
  { value: '**/.git*/**', label: '.git folders', always: true },
  { value: '**/node_modules/**', label: 'node_modules/', initial: true },
  { value: '**/tests/**', label: 'tests/' },
  { value: '**/.env*', label: '.env files (keep the server one safe)', initial: true },
  { value: '**/*.md', label: 'Markdown files (README etc.)' },
  { value: '**/.editorconfig', label: '.editorconfig' },
];

export function secretNames(prefix) {
  return {
    host: `${prefix}HOST`,
    username: `${prefix}USERNAME`,
    password: `${prefix}PASSWORD`,
  };
}

/** Turn a target name like "Staging Server" into a secret prefix CPANEL_STAGING_SERVER_. */
export function prefixFor(target) {
  const t = (target || '').trim();
  if (!t) return 'CPANEL_';
  return `CPANEL_${t.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_|_$/g, '')}_`;
}

export function fileNameFor(target) {
  const t = (target || '').trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return t ? `cpanel-deploy-${t}.yml` : 'cpanel-deploy.yml';
}

export function withSlash(dir) {
  let d = (dir || './').trim().replace(/\\/g, '/');
  if (d === '' || d === '.') d = './';
  return d.endsWith('/') ? d : d + '/';
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const expr = (s) => '${{ ' + s + ' }}';

/**
 * @param {object} o
 * @param {string} o.target        display name, may be empty
 * @param {string} o.prefix        secret prefix, e.g. CPANEL_
 * @param {string} o.branch
 * @param {string} o.localDir
 * @param {string} o.serverDir
 * @param {string} o.protocol      ftp | ftps | ftps-legacy
 * @param {number} [o.port]
 * @param {'strict'|'loose'} [o.security]
 * @param {string[]} o.exclude
 * @param {{enabled:boolean, php:string}} [o.composer]
 * @param {{enabled:boolean, script:string, ci:boolean, version:string}} [o.node]
 */
export function render(o) {
  const s = secretNames(o.prefix);
  const title = o.target ? `Deploy to cPanel (${o.target})` : 'Deploy to cPanel';
  const L = [];
  L.push(`# Generated by cpanel-deploy · ${SITE_URL}`);
  L.push('# Run `npx cpanel-deploy` again any time to change this setup.');
  L.push(`name: ${title}`);
  L.push('');
  L.push('on:');
  L.push('  push:');
  L.push('    branches:');
  L.push(`      - ${q(o.branch)}`);
  L.push('  workflow_dispatch:');
  L.push('');
  L.push('concurrency:');
  L.push(`  group: ${expr('github.workflow')}`);
  L.push('  cancel-in-progress: false');
  L.push('');
  L.push('jobs:');
  L.push('  deploy:');
  L.push(`    name: Upload to ${o.serverDir}`);
  L.push('    runs-on: ubuntu-latest');
  L.push('    steps:');
  L.push('      - name: Checkout');
  L.push(`        uses: ${VERSIONS.checkout}`);

  if (o.composer?.enabled) {
    L.push('');
    L.push('      - name: Setup PHP');
    L.push(`        uses: ${VERSIONS.setupPhp}`);
    L.push('        with:');
    L.push(`          php-version: ${q(o.composer.php)}`);
    L.push('          tools: composer');
    L.push('');
    L.push('      - name: Install Composer dependencies');
    L.push('        run: composer install --no-dev --prefer-dist --no-interaction --no-progress --optimize-autoloader');
  }

  if (o.node?.enabled) {
    L.push('');
    L.push('      - name: Setup Node');
    L.push(`        uses: ${VERSIONS.setupNode}`);
    L.push('        with:');
    L.push(`          node-version: ${q(o.node.version)}`);
    if (o.node.ci) L.push("          cache: 'npm'");
    L.push('');
    L.push('      - name: Build assets');
    L.push('        run: |');
    L.push(`          ${o.node.ci ? 'npm ci' : 'npm install'}`);
    L.push(`          npm run ${o.node.script}`);
  }

  L.push('');
  L.push('      - name: Deploy via FTP');
  L.push(`        uses: ${VERSIONS.ftpDeploy}`);
  L.push('        with:');
  L.push(`          server: ${expr(`secrets.${s.host}`)}`);
  L.push(`          username: ${expr(`secrets.${s.username}`)}`);
  L.push(`          password: ${expr(`secrets.${s.password}`)}`);
  L.push(`          protocol: ${o.protocol}`);
  const def = o.protocol === 'ftps-legacy' ? 990 : 21;
  if (o.port && Number(o.port) !== def) L.push(`          port: ${Number(o.port)}`);
  if (o.security === 'loose') L.push('          security: loose');
  L.push(`          local-dir: ${q(withSlash(o.localDir))}`);
  L.push(`          server-dir: ${q(withSlash(o.serverDir))}`);
  if (o.exclude?.length) {
    L.push('          exclude: |');
    for (const e of o.exclude) L.push(`            ${e}`);
  }
  return L.join('\n') + '\n';
}
